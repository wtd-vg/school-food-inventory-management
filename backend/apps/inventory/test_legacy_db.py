class DiagnoseTests(SimpleTestCase):
    def test_states(self):
        cases = [
            (Facts(APPLIED_OLD | {CONTRACT_MIGRATION}, dict(OLD_TABLES), ()), UP_TO_DATE),
            (Facts(APPLIED_OLD, {}, ()), CLEAN),
            (Facts(frozenset(), {}, ()), CLEAN),
            (Facts(APPLIED_OLD, dict(OLD_TABLES), ()), LEGACY_EMPTY),
            (Facts(APPLIED_OLD, {**OLD_TABLES, "inventory_issue": (3, LEGACY_COLUMNS["inventory_issue"])}, ()), LEGACY_HAS_DATA),
            (Facts(APPLIED_OLD, dict(OLD_TABLES), ("inventory_x.fk_issue",)), BLOCKED),
            (Facts(frozenset({"0007_stocktake_inventoryledger_stocktakeitem"}), dict(OLD_TABLES), ()), UNKNOWN),
            (Facts(APPLIED_OLD, {**OLD_TABLES, "inventory_issue": (0, frozenset({"id", "code"}))}, ()), UNKNOWN),
        ]
        for facts, expected in cases:
            with self.subTest(expected=expected, facts=facts):
                self.assertEqual(diagnose(facts).state, expected)

    def test_data_message_reports_counts(self):
        facts = Facts(APPLIED_OLD, {**OLD_TABLES, "inventory_issueline": (5, LEGACY_COLUMNS["inventory_issueline"])}, ())
        self.assertIn("inventory_issueline=5 dòng", diagnose(facts).message)


