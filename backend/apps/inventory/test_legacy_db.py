class LegacyUpgradeEndToEndTests(TransactionTestCase):
    """Chạy migrate thật hai lần trong DB tạm: chậm hơn các test khác (~30 giây)."""

    def setUp(self):
        self.db_name = f"sf_legacy_{uuid.uuid4().hex[:8]}"
        with connection.cursor() as cursor:
            cursor.execute(f'CREATE DATABASE "{self.db_name}"')
        cfg = connection.settings_dict
        self.env = {
            **os.environ,
            "DB_NAME": self.db_name,
            "DB_HOST": str(cfg["HOST"]),
            "DB_PORT": str(cfg["PORT"]),
            "DB_USER": str(cfg["USER"]),
            "DB_PASSWORD": str(cfg["PASSWORD"]),
            "PYTHONIOENCODING": "utf-8",
        }
        self.env.pop("DATABASE_URL", None)
        self.manage("migrate", "inventory", LEGACY_MIGRATION, "--noinput")
        self.sql(F00048D_ISSUE_DDL)

    def tearDown(self):
        with connection.cursor() as cursor:
            cursor.execute(f'DROP DATABASE IF EXISTS "{self.db_name}" WITH (FORCE)')

    def manage(self, *args, expect=0):
        result = subprocess.run(
            [sys.executable, str(settings.BASE_DIR / "manage.py"), *args],
            env=self.env, capture_output=True, text=True, encoding="utf-8", timeout=300,
        )
        self.assertEqual(result.returncode, expect, msg=f"{args}\n{result.stdout}\n{result.stderr}")
        return result.stdout + result.stderr

    def _connect(self):
        import psycopg

        cfg = connection.settings_dict
        return psycopg.connect(
            host=cfg["HOST"], port=cfg["PORT"], user=cfg["USER"], password=cfg["PASSWORD"],
            dbname=self.db_name, autocommit=True,
        )

    def sql(self, statements):
        with self._connect() as conn:
            conn.execute(statements)

    def scalar(self, query):
        with self._connect() as conn:
            return conn.execute(query).fetchone()[0]

    def test_reproduces_issue_then_upgrades_empty_legacy_db(self):
        out = self.manage("migrate", "--noinput", expect=1)
        self.assertIn('relation "inventory_issue" already exists', out)

        self.assertIn(LEGACY_EMPTY, self.manage("sf_legacy_db_check"))
        self.assertIn("Đã xóa bảng rỗng inventory_issue", self.manage("sf_legacy_db_check", "--apply"))
        self.manage("migrate", "--noinput")
        self.assertIn(UP_TO_DATE, self.manage("sf_legacy_db_check"))
        self.manage("sf31_ledger_audit", "--strict")
        self.manage("makemigrations", "--check", "--dry-run")
        triggers = self.scalar("SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal")
        with connection.cursor() as cursor:
            cursor.execute("SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal")
            self.assertEqual(triggers, cursor.fetchone()[0])

    def test_refuses_legacy_tables_with_data(self):
        self.sql(
            "INSERT INTO auth_user (password, last_login, is_superuser, username, first_name, last_name, email, is_staff, is_active, date_joined) "
            "VALUES ('!', now(), false, 'legacy', '', '', '', false, true, now());"
            "INSERT INTO inventory_issue (code, date, note, status, created_by_id) "
            "SELECT 'PX-CU', '2026-09-29', '', 'draft', id FROM auth_user WHERE username = 'legacy';"
        )
        out = self.manage("sf_legacy_db_check", "--apply", expect=1)
        self.assertIn(LEGACY_HAS_DATA, out)
        self.assertIn("inventory_issue=1 dòng", out)
        self.assertEqual(self.scalar("SELECT count(*) FROM inventory_issue"), 1)


